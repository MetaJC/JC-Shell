export const useI18nStore = defineStore('i18n', () => {
  const saved = (localStorage.getItem(STORAGE_KEY) || '') as Locale
  // 首次启动（无本地存档）时从后端拉取系统 locale 决定默认语言
  // 避免「系统是英文，UI 默认中文，菜单是英文」三处不一致
  const initial: Locale = saved === 'en' || saved === 'zh-CN' ? saved : 'zh-CN'
  const locale = ref<Locale>(initial)

  // 启动时同步：localStorage 已有值表示用户主动选过，保持不动；
  // 没有时拉后端的系统 locale（与后端菜单语言保持一致）
  if (!(saved === 'en' || saved === 'zh-CN')) {
    invoke<string>('get_app_locale')
      .then((sys) => {
        const next: Locale = sys.startsWith('zh') ? 'zh-CN' : 'en'
        if (next !== locale.value) {
          locale.value = next
          document.documentElement.setAttribute('lang', next)
        }
      })
      .catch(() => { /* 非 Tauri 环境或后端失败，保持 zh-CN */ })
  }

  function setLocale(next: Locale) {
    locale.value = next
    try { localStorage.setItem(STORAGE_KEY, next) } catch { /* ignore */ }
    document.documentElement.setAttribute('lang', next)
    // 同步后端：重建 macOS 系统菜单栏 + 通知其他窗口
    invoke('set_app_locale', { locale: next }).catch(() => { /* 后端失败不影响 UI */ })
    notifyPrefsChanged([STORAGE_KEY])
  }

  // 跨窗口同步：其他窗口切换语言后，本窗口重读并应用（仅赋值不重发，无广播环）
  onPrefsChanged((keys) => {
    if (!keys.includes(STORAGE_KEY)) return
    const saved = (localStorage.getItem(STORAGE_KEY) || '') as Locale
    if ((saved === 'en' || saved === 'zh-CN') && saved !== locale.value) {
      locale.value = saved
      document.documentElement.setAttribute('lang', saved)
    }
  })

  // 后端发起的语言变更（如系统设置变更后通过 set_app_locale 触发）同步前端
  // 主要服务于：主窗口已打开时，settings 窗口切语言要立即反映到主窗口
  listen<string>('app:locale-changed', (event) => {
    const v = event.payload
    if (v !== 'zh-CN' && v !== 'en') return
    if (v === locale.value) return
    locale.value = v
    try { localStorage.setItem(STORAGE_KEY, v) } catch { /* ignore */ }
    document.documentElement.setAttribute('lang', v)
  }).catch(() => { /* 非 Tauri 环境忽略 */ })

  function t(key: string, params?: Record<string, string | number>): string {
    const cur = messages[locale.value] || messages['zh-CN']
    let str = cur[key] ?? messages['zh-CN'][key] ?? key
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), String(v))
      })
    }
    // 品牌名统一由 utils/edition.ts 的 appName() 提供，本工程渲染为「JC Shell」。
    if (str.includes('JC Shell')) str = str.split('JC Shell').join(appName())
    return str
  }

  document.documentElement.setAttribute('lang', locale.value)

  return { locale, setLocale, t }
})